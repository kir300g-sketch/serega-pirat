package com.piratechallenge;

import net.minecraft.server.network.ServerPlayerEntity;
import net.minecraft.text.Text;

import java.util.Random;

/** Насмешки Серёги Пирата после каждой смерти. После 5 смертей он начинает твердить про безумие. */
public final class Taunts {
    private static final Random RNG = new Random();

    private static final String[] MOCK = {
            "Ха! Это ты так слушаешь мою музыку? Умер под бит!",
            "Красиво упал. Даже я бы так не смог.",
            "Не повезло. Хотя нет, повезло — я это видел.",
            "Умирать под мои треки — это комплимент, если что.",
            "Ты хоть дослушал? Нет? Ну ладно.",
            "Всё, ты труп. Зато тишина.",
            "Респавн-то бесплатный, а вот репутация — нет.",
            "Ну и кто тут теперь крутой?",
            "Это был мой лучший куплет, а ты его проспал. Вернее, проумирал.",
            "Не плачь. Лучше слушай внимательнее.",
            "Скилл ишью. Диагноз поставил лично я."
    };

    private static final String[] INSANITY = {
            "Знаешь, что такое безумие? Это когда делаешь одно и то же, раз за разом, и ждёшь другого результата.",
            "Безумие — это повторять одно и то же и надеяться, что в этот раз всё будет иначе.",
            "Опять то же самое. Опять смерть. Раз за разом. И ты ждёшь, что будет иначе? Это называется безумие.",
            "Ты умираешь одинаково и удивляешься. Безумие — это повторять одно и то же, ожидая другого.",
            "Раз за разом, раз за разом... Это и есть безумие, друг мой."
    };

    public static void send(ServerPlayerEntity p, int deaths) {
        String line = deaths > 5
                ? INSANITY[RNG.nextInt(INSANITY.length)]
                : MOCK[RNG.nextInt(MOCK.length)];
        p.sendMessage(Text.literal("§6[Серёга Пират] §f" + line), false);
    }

    private Taunts() {}
}
